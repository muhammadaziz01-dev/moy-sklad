/**
 * Agentning tanlangan davr bo'yicha savdo/yig'ilgan summasi.
 * month === "all" → butun yil yig'indisi, aks holda 0..11 oy indeksi.
 * field: "sales" | "collected"
 */
export const getVolume = (agent, year, month, field = "sales") => {
    const arr = agent.volume?.[year]?.[field] || []
    if (month === "all") return arr.reduce((s, v) => s + (v || 0), 0)
    return arr[month] || 0
}

/** Data ichidagi barcha yillar (kamayish tartibida) — filtr uchun */
export const getYears = (list) => {
    const set = new Set()
    list.forEach((a) => Object.keys(a.volume || {}).forEach((y) => set.add(Number(y))))
    return [...set].sort((a, b) => b - a)
}

const sortAgentsByDebt = (agents) => {
    return [...agents].sort((a, b) => b.totalDebt - a.totalDebt);
};

